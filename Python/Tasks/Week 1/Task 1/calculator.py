#Create a simple calculator that performs addition, subtraction, multiplication, and division.


print("Simple Calculator")
#User Input 1
first = float(input("Enter the first number "))
#User Input 2
second = float(input("Enter the second number "))

#Addition
addition = first + second
print("Addition of",first, "and", second, "is", addition)
#Subtraction
subtraction = first - second
print("Subtraction of",first, "and", second, "is", subtraction)
#Multiplication
multiplication = first * second
print("Multiplication of",first, "and", second, "is", multiplication)
#Divison
division = first / second
print("Divison of",first, "and", second, "is", division)
